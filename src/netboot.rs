    #[test]
    fn rootfs_completeness_probe_catches_truncation() {
        // A truncated extraction (missing late-order markers) must fail the
        // probe; a full marker set passes.
        let base = std::env::temp_dir().join(format!("llmtune-rootfs-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&base);
        std::fs::create_dir_all(&base).unwrap();
        // empty tree -> first marker missing
        assert_eq!(rootfs_complete(&base), Err("etc"));
        // partial tree (interrupted mid-usr) -> a later marker missing
        std::fs::create_dir_all(base.join("etc")).unwrap();
        std::fs::create_dir_all(base.join("usr/bin")).unwrap();
        assert_eq!(rootfs_complete(&base), Err("usr/lib/modules"));
        // full marker set -> complete
        std::fs::create_dir_all(base.join("usr/lib/modules")).unwrap();
        std::fs::create_dir_all(base.join("var")).unwrap();
        assert_eq!(rootfs_complete(&base), Ok(()));
        // a FILE where a dir belongs does not count
        std::fs::remove_dir_all(base.join("var")).unwrap();
        std::fs::write(base.join("var"), b"not a dir").unwrap();
        assert_eq!(rootfs_complete(&base), Err("var"));
        let _ = std::fs::remove_dir_all(&base);
    }

