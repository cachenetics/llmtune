//! The netboot (PXE) control plane.
//!
//! llmtune turns a spare host into a BC-250 boot server WITHOUT reinventing the
//! network stack: it orchestrates a proxyDHCP `dnsmasq` (answers only PXE, leaves
//! IP assignment to the LAN router) plus an NFS root, and EMBEDS the artifact +
//! iPXE server (`tiny_http`, already a dep) so it controls exactly what each
//! board boots. A booted board is discovered from the dnsmasq lease file and
//! auto-registered into `fleet.toml` as an `ssh` node, so it flows straight into
//! the fleet cockpit and the `node`/`fleet`/`cluster` commands.
//!
//! Boot chain: firmware PXE -> dnsmasq hands `ipxe.efi` over its built-in TFTP ->
//! iPXE re-requests -> dnsmasq points it at `http://<server>:<port>/boot.ipxe` ->
//! llmtune serves a kernel + NFS-root cmdline -> diskless CachyOS.
//!
//! The config GENERATORS are pure functions (unit-tested); the orchestrator does
//! the privileged IO and previews by default (`--apply` to write), mirroring the
//! rest of llmtune's write commands.

use anyhow::{bail, Context, Result};
use std::path::Path;

use crate::config::Netboot;

/// A resolved netboot config or a clear error explaining it is unconfigured.
pub fn require(cfg: &crate::config::Config) -> Result<&Netboot> {
    cfg.netboot.as_ref().ok_or_else(|| {
        anyhow::anyhow!(
            "netboot is not configured - add a [netboot] section to fleet.toml \
             (interface, server_ip, subnet). See `llmtune netboot init --help`."
        )
    })
}

