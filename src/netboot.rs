/// The proxyDHCP dnsmasq config. proxyDHCP answers ONLY the PXE boot options and
/// leaves address assignment to the LAN's existing DHCP server, so it is safe to
/// run on a shared network (it will not fight the router). Stage 1 hands EFI
/// clients the iPXE NBP over dnsmasq's built-in TFTP; stage 2 (iPXE now running,
/// tagged by its user-class) points at llmtune's HTTP boot script.
pub fn dnsmasq_conf(nb: &Netboot) -> String {
    format!(
        "# AUTO-GENERATED by llmtune (`llmtune netboot init`). Edit fleet.toml,\n\
         # not this file - re-running init overwrites it.\n\
         # proxyDHCP: PXE-only, the LAN router still assigns IPs.\n\
         port=0\n\
         log-dhcp\n\
         dhcp-no-override\n\
         \n\
         # Only serve PXE on the boot NIC; never assign addresses.\n\
         interface={iface}\n\
         bind-interfaces\n\
         dhcp-range={subnet},proxy\n\
         \n\
         # Client-arch + iPXE detection.\n\
         dhcp-match=set:efi64,option:client-arch,7\n\
         dhcp-match=set:efi64,option:client-arch,9\n\
         dhcp-userclass=set:ipxe,iPXE\n\
         \n\
         # Stage 1: firmware -> iPXE NBP over TFTP. Stage 2: iPXE -> HTTP script.\n\
         dhcp-boot=tag:efi64,tag:!ipxe,ipxe.efi,,{ip}\n\
         dhcp-boot=tag:ipxe,{base}/boot.ipxe\n\
         \n\
         # dnsmasq's built-in TFTP serves only ipxe.efi (no tftp-hpa needed).\n\
         enable-tftp\n\
         tftp-root={tftp}\n",
        iface = nb.interface,
        subnet = nb.subnet,
        ip = nb.server_ip,
        base = nb.http_base(),
        tftp = nb.tftp_root,
    )
}

/// The `/etc/exports` line for the read-only diskless root.
///
/// Deliberate posture, documented in the README's security notes:
/// `ro` (nodes never write the shared root) + `no_root_squash` (the diskless
/// nodes' root must read root-owned files in the image). The export CIDR IS
/// the security boundary - every host inside it can read the full root image,
/// so `lan_cidr` must be the narrow fleet subnet, never a wide range.
pub fn nfs_exports(nb: &Netboot) -> String {
    format!(
        "# AUTO-GENERATED by llmtune (`llmtune netboot init`).\n\
         {root} {cidr}(ro,sync,no_subtree_check,no_root_squash)\n",
        root = nb.rootfs,
        cidr = nb.export_cidr(),
    )
}

/// The dynamic iPXE boot script llmtune serves at `/boot.ipxe`. `mac` (when the
/// board passes `${net0/mac}`) lets a future per-node override vary the profile;
/// for now every board gets the same NFS-root boot with the configured OC
/// profile baked into the kernel cmdline for the image's tuner to read.
pub fn boot_ipxe(nb: &Netboot, _mac: Option<&str>) -> String {
    format!(
        "#!ipxe\n\
         kernel {base}/vmlinuz root=nfs:{ip}:{root} ip=dhcp rw rd.neednet=1 \
         amd_pstate=passive idle=amd_hwp llmtune.oc={oc}\n\
         initrd {base}/initramfs-nfs.img\n\
         boot\n",
        base = nb.http_base(),
        ip = nb.server_ip,
        root = nb.rootfs,
        oc = nb.oc_profile,
    )
}

/// The systemd unit that runs llmtune's artifact/iPXE server. `exe` is llmtune's
/// own path so the unit survives a binary move only if reinstalled in place (the
/// same contract as `setup`'s generated unit).
pub fn http_unit(exe: &str, user: &str, port: u16, config: Option<&str>) -> String {
    let cfg_arg = config.map(|c| format!(" --config {c}")).unwrap_or_default();
    format!(
        "# AUTO-GENERATED by llmtune (`llmtune netboot init`).\n\
         [Unit]\n\
         Description=llmtune netboot artifact + iPXE server\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         \n\
         [Service]\n\
         ExecStart={exe} netboot serve --port {port}{cfg_arg}\n\
         Restart=on-failure\n\
         RestartSec=2\n\
         User={user}\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
    )
}

